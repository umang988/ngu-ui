const BUILT_IN: Record<Lang, Partial<Record<keyof NguMessages, string>>> = { en: {}, hi: HI, ar: AR };

/**
 * One lookup for everything, the way an i18n library would work: ngu-form asks for
 * `ngu.<message>` and for the app's keys. Returning undefined keeps the original text.
 */
export function translate(lang: Lang, key: string): string | undefined {
  if (key.startsWith('ngu.')) {
    return BUILT_IN[lang][key.slice(4) as keyof NguMessages];
  }
  return APP[lang][key];
}
