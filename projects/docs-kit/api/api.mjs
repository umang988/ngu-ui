// The public API of a built package, read from its .d.ts files with the TypeScript compiler.
//
//   node projects/docs-kit/api/api.mjs dist/ngu-form --report api --docs projects/demo/src/app/docs/reference
//   ... --check   compare with the committed files instead of writing them, and fail on any
//                 difference or on exports without TSDoc
//
// Writes `<report>/<package>.api.md`, every export's declaration without comments, so a pull
// request shows each public API change, and with --docs one JSON file per entry point for the
// docs site's reference pages.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import ts from 'typescript';

const argv = process.argv.slice(2);
const pkgDir = argv[0];
const option = (name) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : undefined);
const reportDir = option('--report');
const docsDir = option('--docs');
const check = argv.includes('--check');
if (!pkgDir || !reportDir) {
  console.error('Usage: node api.mjs <dist/package> --report <dir> [--docs <dir>] [--check]');
  process.exit(1);
}

const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
const entries = Object.entries(pkg.exports ?? {})
  .filter(([, value]) => typeof value === 'object' && value.types)
  .map(([key, value]) => ({
    name: key === '.' ? pkg.name : `${pkg.name}/${key.slice(2)}`,
    file: resolve(pkgDir, value.types),
  }));

const program = ts.createProgram(
  entries.map((e) => e.file),
  { noEmit: true, skipLibCheck: true, strict: true, target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, moduleResolution: ts.ModuleResolutionKind.Bundler },
);
const checker = program.getTypeChecker();
const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });

const undocumented = [];
const report = [`# ${pkg.name} public API`, '', '<!-- Generated by projects/docs-kit/api/api.mjs from the built .d.ts files. Do not edit. -->', ''];
const docs = {};

for (const entry of entries) {
  const source = program.getSourceFile(entry.file);
  const module = checker.getSymbolAtLocation(source);
  const symbols = checker
    .getExportsOfModule(module)
    .map((exported) => ({ exported, symbol: exported.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(exported) : exported }))
    .sort((a, b) => a.exported.name.localeCompare(b.exported.name));

  report.push(`## ${entry.name}`, '', '```ts');
  const items = [];
  for (const { exported, symbol } of symbols) {
    const declarations = (symbol.declarations ?? []).filter((d) => !ts.isModuleDeclaration(d));
    if (declarations.length === 0) {
      continue;
    }
    const item = describe(exported.name, symbol, declarations, source);
    report.push(item.signature, '');
    if (!item.summary && !item.deprecated) {
      undocumented.push(`${entry.name}: ${exported.name}`);
    }
    for (const member of item.members ?? []) {
      if (!member.description && !member.name.startsWith('[')) {
        undocumented.push(`${entry.name}: ${exported.name}.${member.name}`);
      }
    }
    items.push(item);
  }
  // `declare module 'ngu-form' { interface NguFieldTypeMap { ... } }`: types this entry adds.
  for (const statement of source.statements) {
    if (!ts.isModuleDeclaration(statement) || !ts.isStringLiteral(statement.name) || !statement.body || !ts.isModuleBlock(statement.body)) {
      continue;
    }
    const name = `declare module '${statement.name.text}'`;
    const members = statement.body.statements
      .filter(ts.isInterfaceDeclaration)
      .flatMap((i) => i.members.flatMap((m) => memberOf(m, {}).map((r) => ({ ...r, name: `${i.name.text}.${r.name}` }))));
    report.push(print(statement), '');
    for (const member of members) {
      if (!member.description) undocumented.push(`${entry.name}: ${name} ${member.name}`);
    }
    items.push({ name, kind: 'augmentation', summary: `Adds to the interfaces of \`${statement.name.text}\`.`, signature: print(statement), members });
  }
  if (report.at(-1) === '') {
    report.pop();
  }
  report.push('```', '');
  docs[entry.name] = { entry: entry.name, symbols: items };
}

const outputs = new Map([[join(reportDir, `${pkg.name}.api.md`), report.join('\n')]]);
if (docsDir) {
  for (const [name, data] of Object.entries(docs)) {
    outputs.set(join(docsDir, `${name.replace('/', '-')}.json`), JSON.stringify(data, null, 1) + '\n');
  }
}

if (check) {
  const stale = [...outputs].filter(([file, text]) => !existsSync(file) || readFileSync(file, 'utf8') !== text).map(([file]) => file);
  if (stale.length) {
    console.error(`The public API changed. If that is intended, run \`npm run api:update\` and commit:\n  ${stale.join('\n  ')}`);
    showDiff(stale[0], outputs.get(stale[0]));
  }
  if (undocumented.length) {
    console.error(`Exports without TSDoc (${undocumented.length}):\n  ${undocumented.join('\n  ')}`);
  }
  if (stale.length || undocumented.length) {
    process.exit(1);
  }
  console.log(`${pkg.name}: API report and reference data are up to date; every export is documented.`);
} else {
  for (const [file, text] of outputs) {
    mkdirSync(resolve(file, '..'), { recursive: true });
    writeFileSync(file, text);
  }
  console.log(`${pkg.name}: wrote ${outputs.size} files. ${undocumented.length} exports or members without TSDoc.`);
  if (undocumented.length && argv.includes('--list')) {
    console.log(undocumented.join('\n'));
  }
}

/** One export: its kind, declaration text, TSDoc and, for classes and interfaces, members. */
function describe(name, symbol, declarations, source) {
  const first = declarations[0];
  const doc = docOf(symbol);
  const item = { name, kind: kindOf(first), summary: doc.text, signature: '' };
  if (doc.deprecated !== undefined) item.deprecated = doc.deprecated || 'Deprecated.';
  if (doc.examples.length) item.examples = doc.examples;

  if (ts.isClassDeclaration(first)) {
    const meta = angularMeta(first);
    if (meta) Object.assign(item, meta);
    const members = first.members.filter(isPublicMember);
    item.members = members.flatMap((m) => memberOf(m, meta?.inputs ?? {}));
    const head = print(ts.factory.updateClassDeclaration(first, first.modifiers, first.name, first.typeParameters, first.heritageClauses, []), source);
    const body = members.map((m) => '    ' + print(m).replace(/\n/g, '\n    '));
    item.signature = body.length ? head.replace(/\{\s*\}$/, `{\n${body.join('\n')}\n}`) : head;
  } else if (ts.isInterfaceDeclaration(first)) {
    // Augmentations from other entry points are listed with those entry points.
    const own = declarations.filter((d) => d.getSourceFile() === source);
    item.members = own.flatMap((d) => (ts.isInterfaceDeclaration(d) ? d.members.flatMap((m) => memberOf(m, {})) : []));
    item.signature = own.map(print).join('\n');
  } else if (ts.isVariableDeclaration(first)) {
    item.signature = `export declare const ${name}: ${first.type ? print(first.type) : checker.typeToString(checker.getTypeOfSymbol(symbol))};`;
  } else {
    item.signature = declarations.map(print).join('\n');
  }
  item.signature = item.signature.replace(/^(?!export )/gm, (_, offset) => (offset === 0 && !/^(export|declare)/.test(item.signature) ? 'export ' : ''));
  return item;
}

function kindOf(node) {
  if (ts.isFunctionDeclaration(node)) return 'function';
  if (ts.isClassDeclaration(node)) return 'class';
  if (ts.isInterfaceDeclaration(node)) return 'interface';
  if (ts.isTypeAliasDeclaration(node)) return 'type';
  if (ts.isEnumDeclaration(node)) return 'enum';
  if (ts.isVariableDeclaration(node)) return 'const';
  return ts.SyntaxKind[node.kind];
}

function isPublicMember(member) {
  const name = member.name && ts.isIdentifier(member.name) ? member.name.text : member.name?.getText?.() ?? '';
  if (name.startsWith('ɵ') || (member.name && ts.isPrivateIdentifier(member.name))) return false;
  const flags = ts.getCombinedModifierFlags(member);
  return !(flags & (ts.ModifierFlags.Private | ts.ModifierFlags.Protected));
}

/** Selector and inputs of an Angular component or directive, from its `ɵcmp` / `ɵdir` type. */
function angularMeta(node) {
  for (const member of node.members) {
    const name = member.name?.getText?.();
    if ((name !== 'ɵcmp' && name !== 'ɵdir') || !member.type || !ts.isTypeReferenceNode(member.type)) continue;
    const [, selector, , inputs] = member.type.typeArguments ?? [];
    const meta = {
      kind: name === 'ɵcmp' ? 'component' : 'directive',
      selector: selector && ts.isLiteralTypeNode(selector) ? selector.literal.text : undefined,
      inputs: {},
    };
    if (inputs && ts.isTypeLiteralNode(inputs)) {
      for (const input of inputs.members) {
        const text = input.type?.getText() ?? '';
        meta.inputs[stripQuotes(input.name.getText())] = {
          alias: /"alias":\s*"([^"]+)"/.exec(text)?.[1],
          required: /"required":\s*true/.test(text),
        };
      }
    }
    return meta;
  }
  return undefined;
}

function memberOf(member, inputs) {
  if (ts.isConstructorDeclaration(member)) return [];
  const symbol = member.name ? checker.getSymbolAtLocation(member.name) : undefined;
  const doc = symbol ? docOf(symbol) : { text: '', examples: [] };
  let name = member.name ? stripQuotes(member.name.getText()) : '';
  let type = member.type ? print(member.type) : '';
  let kind = ts.isMethodSignature(member) || ts.isMethodDeclaration(member) ? 'method' : 'property';
  if (ts.isIndexSignatureDeclaration(member)) {
    name = `[${member.parameters.map(print).join(', ')}]`;
    kind = 'index';
  }
  if (kind === 'method') {
    type = print(member).replace(/^[^(<]*/, '');
  }
  const signal = /^(?:i0\.|import\("@angular\/core"\)\.)?(InputSignal(?:WithTransform)?|ModelSignal|OutputEmitterRef|OutputRef)<(.*)>$/s.exec(type);
  type = type.replace(/import\("[^"]+"\)\./g, '').replace(/\bi0\./g, '');
  const result = { name, kind, type, description: doc.text };
  if (signal) {
    const [, wrapper, args] = signal;
    result.kind = wrapper.startsWith('Input') ? 'input' : wrapper === 'ModelSignal' ? 'model' : 'output';
    result.type = wrapper === 'InputSignalWithTransform' ? splitTypeArgs(args)[1] : args;
    const meta = inputs[name];
    if (meta?.alias && meta.alias !== name) result.name = meta.alias;
    if (meta?.required) result.required = true;
  }
  if (member.questionToken) result.optional = true;
  if (doc.deprecated !== undefined) result.deprecated = doc.deprecated || 'Deprecated.';
  const fallback = doc.defaultValue;
  if (fallback) result.default = fallback;
  return [result];
}

/** TSDoc as plain text (backticks kept, `{@link X}` as `X`), with `@example` blocks apart. */
function docOf(symbol) {
  const text = ts.displayPartsToString(symbol.getDocumentationComment(checker)).trim();
  const tags = symbol.getJsDocTags(checker);
  const tag = (name) => tags.find((t) => t.name === name);
  const tagText = (t) => (t?.text ? ts.displayPartsToString(t.text).trim() : t ? '' : undefined);
  return {
    text: cleanLinks(text),
    deprecated: tagText(tag('deprecated')),
    defaultValue: tagText(tag('default') ?? tag('defaultValue')),
    examples: tags.filter((t) => t.name === 'example').map((t) => cleanLinks(tagText(t))),
  };
}

function cleanLinks(text) {
  return text.replace(/\{@link(?:code|plain)?\s+([^}\s|]+)(?:[\s|]+([^}]*))?\}/g, (_, target, label) => `\`${(label || target).trim()}\``);
}

/** Declaration text without comments. Synthesized nodes need the file their parts come from. */
function print(node, source = node.getSourceFile?.()) {
  return printer.printNode(ts.EmitHint.Unspecified, node, source ?? ts.createSourceFile('x.ts', '', ts.ScriptTarget.ES2022)).trim();
}

function stripQuotes(text) {
  return text.replace(/^["']|["']$/g, '');
}

/** Splits `A, B<C, D>` at its top-level commas. */
function splitTypeArgs(text) {
  const parts = [];
  let depth = 0;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (c === '<' || c === '(' || c === '{' || c === '[') depth++;
    else if (c === '>' || c === ')' || c === '}' || c === ']') depth--;
    else if (c === ',' && depth === 0) {
      parts.push(text.slice(start, i).trim());
      start = i + 1;
    }
  }
  parts.push(text.slice(start).trim());
  return parts;
}

function showDiff(file, expected) {
  if (!existsSync(file)) return;
  const old = readFileSync(file, 'utf8').split('\n');
  const now = expected.split('\n');
  const removed = old.filter((line) => !now.includes(line)).slice(0, 15);
  const added = now.filter((line) => !old.includes(line)).slice(0, 15);
  console.error(`\nIn ${file}:\n${removed.map((l) => `- ${l}`).join('\n')}\n${added.map((l) => `+ ${l}`).join('\n')}`);
}
